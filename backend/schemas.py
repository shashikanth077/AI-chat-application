from datetime import datetime
from typing import Annotated, Literal

from pydantic import AfterValidator, BaseModel, ConfigDict, Field, model_validator

# Limits live in one place so Phase 6 / README can reference them.
MAX_MESSAGE_CHARS = 4000
MAX_HISTORY_MESSAGES = 20


def _not_blank(value: str) -> str:
    value = value.strip()
    if not value:
        raise ValueError("content must not be blank")
    return value


# One definition of "valid message text", reused by every schema that has it.
MessageContent = Annotated[
    str,
    Field(min_length=1, max_length=MAX_MESSAGE_CHARS),
    AfterValidator(_not_blank),
]


class ChatMessage(BaseModel):
    # Literal: only these exact strings are accepted. The client can never
    # smuggle in a "system" message to override our instructions.
    role: Literal["user", "assistant"]
    content: MessageContent


class ChatRequest(BaseModel):
    messages: list[ChatMessage] = Field(min_length=1, max_length=MAX_HISTORY_MESSAGES)

    @model_validator(mode="after")
    def last_message_is_user(self) -> "ChatRequest":
        if self.messages[-1].role != "user":
            raise ValueError("the last message must have role 'user'")
        return self


class ChatResponse(BaseModel):
    reply: str


# ---- Conversations (Phase 11) ----


class NewMessageRequest(BaseModel):
    """The only thing a client sends: the new text. History is stored server-side."""

    content: MessageContent
    # Generated by the client per user message. Re-sending the same id is a
    # retry: the server won't store the message twice.
    client_message_id: str = Field(min_length=8, max_length=64)


class ConversationSummary(BaseModel):
    model_config = ConfigDict(from_attributes=True)  # allow building from ORM objects

    id: str
    title: str
    updated_at: datetime


class StoredMessage(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: int
    role: Literal["user", "assistant"]
    content: str


class ConversationDetail(ConversationSummary):
    messages: list[StoredMessage]


# ---- Documents / retrieval (Phase 12) ----

MAX_SEARCH_QUERY_CHARS = 500
MAX_TOP_K = 10


class DocumentSummary(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: str
    filename: str
    size_bytes: int
    chunk_count: int
    created_at: datetime


class SearchRequest(BaseModel):
    query: Annotated[str, Field(min_length=1, max_length=MAX_SEARCH_QUERY_CHARS), AfterValidator(_not_blank)]
    top_k: int = Field(default=4, ge=1, le=MAX_TOP_K)


class SearchResult(BaseModel):
    document_id: str
    filename: str
    position: int
    text: str
    score: float
